# Имитация списка логов, которые приходят с бэкенд-сервера
# В реальной работе такие данные будут приходить из файла или базы данных
logs = [
    "INFO: Пользователь Иван вошел в систему",
    "ERROR: Не удалось подключиться к базе данных",
    "INFO: Платеж успешно проведен",
    "WARNING: Мало места на диске",
    "ERROR: Ошибка авторизации пользователя"
]

print("--- ПОИСК ОШИБОК В СИСТЕМЕ ---")

# Проходим циклом по каждому логу в списке
for log in logs:
    # Метод .startswith() проверяет, начинается ли строка с указанного текста
    if log.startswith("ERROR:"):
        # Если строка начинается с "ERROR:", выводим её на экран
        print(f"🚨 Найдена критическая ошибка: {log}")