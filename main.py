# Исходные логи с сервера
logs = [
    "INFO: Система успешно запущена",
    "ERROR: Сбой подключения к базе данных",
    "WARNING: Мало свободного места на диске",
    "ERROR: Ошибка авторизации пользователя"
]

# Открываем файл для ЗАПИСИ ('w' — write). 
# Если файла с таким именем ещё нет, Python сам создаст его в папке проекта!
with open("error_report.txt", "w", encoding="utf-8") as report_file:
    
    # Проходим по всем логам
    for log in logs:
        if "ERROR:" in log:
            # Записываем найденную ошибку в наш новый файл.
            # \n в конце нужен для того, чтобы каждая ошибка шла с новой строки.
            report_file.write(log + "\n")

print("Готово! Отчёт по ошибкам успешно записан в файл error_report.txt.")